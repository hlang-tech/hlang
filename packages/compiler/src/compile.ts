/**
 * `compile` turns an `IGraph` into a standalone ES module.
 *
 * Pipeline: `planGraph` (shared with the interpreter) → ESTree program → text.
 * The emitted module exports `run(options)`, which performs the plan's steps
 * exactly as `@hlang-org/interpreter` does: construct every node with
 * `{ nodeId, flowId, env, middleware, config, signal }`, wire each connection
 * as `source.O(port).connect(target.I(port))`, and run every Readable root.
 * `compile` itself is pure: it performs no IO and installs nothing.
 */

import { generate } from 'astring';
import type { Expression, ImportDeclaration, MemberExpression, Program, Statement, VariableDeclaration } from 'estree';
import { ERROR_PORT_NAME, planGraph } from '@hlang-org/ir';
import type { ExecutionPlan, IGraph } from '@hlang-org/ir';
import { CompileError } from './errors';
import {
  array,
  arrow,
  binary,
  block,
  call,
  constant,
  construct,
  id,
  index,
  isIdentifierName,
  logical,
  member,
  num,
  object,
  property,
  spread,
  statement,
  str,
  typeOf,
  valueToExpression,
} from './estree';

/** Where a node class comes from: an ES module and one of its exports. */
export interface NodeImport {
  /** Module specifier written into the generated `import` (package name, path, or URL). */
  readonly from: string;
  /** Export name. Defaults to the module's default export. */
  readonly name?: string;
}

/** Options for {@link compile}. */
export interface CompileOptions {
  /** The import for every node `code` used by the graph. */
  readonly nodes: Readonly<Record<string, NodeImport>>;
  /** Module that exports the runtime `Flow`. Defaults to `@hlang-org/runtime`. */
  readonly runtime?: string;
  /** Module that exports RxJS `Subject`, used for the stop signal. Defaults to `rxjs`. */
  readonly rxjs?: string;
}

/** The compiled program. */
export interface CompileResult {
  /** ES module source. Exports `run(options?)`. */
  readonly code: string;
  /** Every module specifier the program imports, in import order. */
  readonly imports: readonly string[];
}

const DEFAULT_RUNTIME = '@hlang-org/runtime';
const DEFAULT_RXJS = 'rxjs';
const DEFAULT_ENV = 'prod';
const HEADER = '// Generated by @hlang-org/compiler. Do not edit.\n';

/** Compile `graph` to an ES module. Throws `GraphError` or `CompileError`. */
export function compile(graph: IGraph, options: CompileOptions): CompileResult {
  const plan = planGraph(graph);
  const runtime = options.runtime ?? DEFAULT_RUNTIME;
  const rxjs = options.rxjs ?? DEFAULT_RXJS;

  const nodeImports = resolveNodeImports(plan, options.nodes);
  const imports: ImportDeclaration[] = [
    namedImport(runtime, 'Flow', 'Flow'),
    namedImport(rxjs, 'Subject', 'Subject'),
    ...nodeImports.declarations,
  ];

  const program: Program = {
    type: 'Program',
    sourceType: 'module',
    body: [
      ...imports,
      {
        type: 'ExportNamedDeclaration',
        declaration: {
          type: 'FunctionDeclaration',
          id: id('run'),
          params: [{ type: 'AssignmentPattern', left: id('options'), right: object([]) }],
          body: block(runBody(plan, nodeImports.localByCode)),
          generator: false,
          async: false,
        },
        specifiers: [],
        source: null,
        attributes: [],
      },
    ],
  };

  return {
    code: HEADER + generate(program),
    imports: imports.map((declaration) => String(declaration.source.value)),
  };
}

interface ResolvedImports {
  readonly declarations: ImportDeclaration[];
  readonly localByCode: ReadonlyMap<string, string>;
}

/** One import per distinct (module, export); locals are `Node0`, `Node1`, … in first-use order. */
function resolveNodeImports(plan: ExecutionPlan, nodes: CompileOptions['nodes']): ResolvedImports {
  const declarations: ImportDeclaration[] = [];
  const localByKey = new Map<string, string>();
  const localByCode = new Map<string, string>();

  for (const planned of plan.nodes) {
    if (localByCode.has(planned.code)) {
      continue;
    }
    const target = Object.prototype.hasOwnProperty.call(nodes, planned.code) ? nodes[planned.code] : undefined;
    if (target === undefined) {
      throw new CompileError(
        'unresolved-node',
        `No import is configured for node code "${planned.code}" (node "${planned.nodeId}").`,
      );
    }
    const exportName = target.name ?? 'default';
    if (exportName !== 'default' && !isIdentifierName(exportName)) {
      throw new CompileError(
        'invalid-import',
        `Export name "${exportName}" for node code "${planned.code}" is not a valid identifier.`,
      );
    }
    const key = `${target.from}\u0000${exportName}`;
    let local = localByKey.get(key);
    if (local === undefined) {
      local = `Node${String(localByKey.size)}`;
      localByKey.set(key, local);
      declarations.push(
        exportName === 'default'
          ? {
              type: 'ImportDeclaration',
              specifiers: [{ type: 'ImportDefaultSpecifier', local: id(local) }],
              source: str(target.from),
              attributes: [],
            }
          : namedImport(target.from, exportName, local),
      );
    }
    localByCode.set(planned.code, local);
  }

  return { declarations, localByCode };
}

function namedImport(from: string, imported: string, local: string): ImportDeclaration {
  return {
    type: 'ImportDeclaration',
    specifiers: [{ type: 'ImportSpecifier', imported: id(imported), local: id(local) }],
    source: str(from),
    attributes: [],
  };
}

/** The statements of `run(options = {})`. */
function runBody(plan: ExecutionPlan, localByCode: ReadonlyMap<string, string>): Statement[] {
  const options = id('options');
  const nodes = id('nodes');
  const nodeRef = (nodeId: string): MemberExpression => index(nodes, nodeId);
  const fallback = (name: string, value: Expression): VariableDeclaration =>
    constant(name, logical('??', member(options, name), value));

  // Default flow id when the caller passes none: `flow-` + a base-36 timestamp.
  const generatedFlowId = binary('+', str('flow-'), call(member(call(member(id('Date'), 'now')), 'toString'), [num(36)]));

  const errorSources = plan.nodes.filter((planned) => planned.kind !== 'W').map((planned) => planned.nodeId);

  const body: Statement[] = [
    fallback('flowId', generatedFlowId),
    fallback('env', str(DEFAULT_ENV)),
    // A frozen copy of the host's middleware, as the interpreter passes it.
    constant(
      'middleware',
      call(member(id('Object'), 'freeze'), [object([spread(logical('??', member(options, 'middleware'), object([])))])]),
    ),
    // Stop signal, shaped like the interpreter's IStopSignal.
    constant('stop', construct(id('Subject'))),
    constant('stopCallbacks', array([])),
    constant(
      'signal',
      object([
        property('observable', call(member(id('stop'), 'asObservable'))),
        property(
          'onStop',
          arrow([id('callback')], block([statement(call(member(id('stopCallbacks'), 'push'), [id('callback')]))])),
        ),
      ]),
    ),
    // 1. Construct every node.
    constant(
      'nodes',
      object(
        plan.nodes.map((planned) => {
          const local = localByCode.get(planned.code);
          if (local === undefined) {
            // Unreachable: resolveNodeImports covers every planned code.
            throw new CompileError('unresolved-node', `No import resolved for node code "${planned.code}".`);
          }
          return property(
            planned.nodeId,
            construct(id(local), [
              object([
                property('nodeId', str(planned.nodeId)),
                property('flowId', id('flowId'), true),
                property('env', id('env'), true),
                property('middleware', id('middleware'), true),
                property('config', valueToExpression(planned.config, `nodes[${JSON.stringify(planned.nodeId)}].config`)),
                property('signal', id('signal'), true),
              ]),
            ]),
          );
        }),
      ),
    ),
  ];

  // 2. Report errors from every Readable and Transform node, before running.
  if (errorSources.length > 0) {
    body.push({
      type: 'IfStatement',
      test: member(options, 'onError'),
      consequent: block([
        constant('onError', member(options, 'onError')),
        {
          type: 'ForOfStatement',
          await: false,
          left: { type: 'VariableDeclaration', kind: 'const', declarations: [{ type: 'VariableDeclarator', id: id('nodeId'), init: null }] },
          right: array(errorSources.map(str)),
          body: block([
            statement(
              call(member(call(member({ type: 'MemberExpression', object: nodes, property: id('nodeId'), computed: true, optional: false }, 'O'), [str(ERROR_PORT_NAME)]), 'receive'), [
                arrow(
                  [id('error')],
                  call(id('onError'), [object([property('nodeId', id('nodeId'), true), property('error', id('error'), true)])]),
                ),
              ]),
            ),
          ]),
        },
      ]),
      alternate: null,
    });
  }

  // 3. Wire every connection: source.O(port).connect(target.I(port)).
  for (const { source, target } of plan.connections) {
    body.push(
      statement(
        call(member(call(member(nodeRef(source.nodeId), 'O'), [str(source.portId)]), 'connect'), [
          call(member(nodeRef(target.nodeId), 'I'), [str(target.portId)]),
        ]),
      ),
    );
  }

  // 4. Run every Readable root.
  body.push(constant('flow', construct(id('Flow'))));
  for (const root of plan.roots) {
    body.push(statement(call(member(id('flow'), 'run'), [nodeRef(root)])));
  }

  // The handle: same shape as the interpreter's (flowId, nodes, dispose).
  body.push({
    type: 'ReturnStatement',
    argument: object([
      property('flowId', id('flowId'), true),
      property('nodes', nodes, true),
      property(
        'dispose',
        arrow(
          [],
          block([
            statement(call(member(id('stop'), 'next'))),
            statement(call(member(id('stop'), 'complete'))),
            {
              type: 'ForOfStatement',
              await: false,
              left: { type: 'VariableDeclaration', kind: 'const', declarations: [{ type: 'VariableDeclarator', id: id('callback'), init: null }] },
              right: id('stopCallbacks'),
              body: block([statement(call(id('callback')))]),
            },
            // Dispose the flow (node teardowns, closed ports) on a runtime
            // that provides it, as the interpreter does.
            {
              type: 'IfStatement',
              test: binary('===', typeOf(member(id('flow'), 'dispose')), str('function')),
              consequent: block([statement(call(member(id('flow'), 'dispose')))]),
              alternate: null,
            },
          ]),
        ),
      ),
    ]),
  });

  return body;
}

