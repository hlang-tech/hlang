import type { Metadata } from 'next';
import Link from 'next/link';
import { notFound } from 'next/navigation';
import { DocArticle } from '@/components/docs/DocArticle';
import { getApiMarkdown, getApiPackages, getNeighbours } from '@/lib/docs';
import { renderMarkdown } from '@/lib/markdown';
import { SITE } from '@/lib/site';

export const dynamicParams = false;

export function generateStaticParams() {
  return getApiPackages().map(item => ({ pkg: item.short }));
}

interface Params {
  readonly params: Promise<{ readonly pkg: string }>;
}

export async function generateMetadata({ params }: Params): Promise<Metadata> {
  const { pkg } = await params;
  const item = getApiPackages().find(entry => entry.short === pkg);
  return item === undefined
    ? {}
    : { title: `${item.name} API`, description: item.description, alternates: { canonical: `/docs/api/${item.short}` } };
}

export default async function ApiPage({ params }: Params) {
  const { pkg } = await params;
  const item = getApiPackages().find(entry => entry.short === pkg);
  const markdown = getApiMarkdown(pkg);
  if (item === undefined || markdown === undefined) {
    notFound();
  }
  const { html, toc } = await renderMarkdown(markdown);
  const { previous, next } = getNeighbours(`/docs/api/${pkg}`);
  return (
    <DocArticle
      title={item.name}
      description={`${item.description} Version ${item.version}, ${String(item.exports)} exports.`}
      html={html}
      toc={toc.filter(entry => entry.depth === 2 || toc.length < 40)}
      previous={previous}
      next={next}
      source={
        <>
          Generated by TypeDoc from{' '}
          <Link
            href={`${SITE.repository}/tree/main/packages/${pkg}/src`}
            target="_blank"
            rel="noreferrer"
            className="underline decoration-silver-lo underline-offset-4 hover:text-ink"
          >
            packages/{pkg}/src
          </Link>{' '}
          at build time.
        </>
      }
    />
  );
}
