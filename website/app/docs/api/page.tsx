import type { Metadata } from 'next';
import Link from 'next/link';
import { getApiPackages, getNeighbours } from '@/lib/docs';

export const metadata: Metadata = {
  title: 'API reference',
  description: 'The public API of every hlang package, generated from source by TypeDoc.',
  alternates: { canonical: '/docs/api' },
};

export default function ApiIndex() {
  const packages = getApiPackages();
  const { next } = getNeighbours('/docs/api');
  return (
    <div className="max-w-[72ch]">
      <h1 className="text-l font-semibold tracking-[-0.035em]">API reference</h1>
      <p className="mt-5 text-s text-muted">
        Generated by TypeDoc from each package&apos;s public entry point at every build: exports, signatures and
        comments come from the source, and every entry links to the line that defines it.
      </p>
      <ul className="mt-12 border-t border-line">
        {packages.map(item => (
          <li key={item.short} className="border-b border-line">
            <Link href={`/docs/api/${item.short}`} className="group grid gap-1 py-4 sm:grid-cols-[minmax(0,1fr)_auto] sm:items-baseline sm:gap-6">
              <span className="text-s font-medium text-ink group-hover:text-silver">{item.name}</span>
              <span className="text-xs tabular-nums text-muted">
                {item.version} · {item.exports} exports
              </span>
              <span className="text-s text-muted sm:col-span-2">{item.description}</span>
            </Link>
          </li>
        ))}
      </ul>
      {next === undefined ? null : (
        <p className="mt-10 text-s">
          <Link href={next.href} className="underline decoration-silver-lo underline-offset-4 hover:decoration-ink">
            Start with {next.title}
          </Link>
        </p>
      )}
    </div>
  );
}
